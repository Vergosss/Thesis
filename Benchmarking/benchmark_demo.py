import torch
import time
from transformers import AutoModelForSequenceClassification, TrainingArguments, Trainer, TrainerCallback
from datasets import load_dataset
import evaluate
from transformers import AutoTokenizer
import numpy as np

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(device)
imdb = load_dataset("stanfordnlp/imdb") #Demo Dataset
imdb['train'] = imdb['train'].shuffle(seed=42).select(range(1000))
imdb['test'] = imdb['test'].shuffle(seed=42).select(range(100))

train_count = imdb["train"].num_rows
test_count  = imdb["test"].num_rows

print("Train samples:", train_count)
print("Test samples:", test_count)

input('WAIT')
##########
tokenizer = AutoTokenizer.from_pretrained("distilbert/distilbert-base-uncased")
def preprocess_function(examples):
    return tokenizer(examples["text"],padding='max_length' ,truncation=True)
####################
tokenized_imdb = imdb.map(preprocess_function, batched=True)
accuracy = evaluate.load("accuracy")
def compute_metrics(eval_pred):
    predictions, labels = eval_pred
    predictions = np.argmax(predictions, axis=1)
    return accuracy.compute(predictions=predictions, references=labels)

model = AutoModelForSequenceClassification.from_pretrained(
    "distilbert/distilbert-base-uncased", num_labels=2)
original = model
model = model.to(device)
#########
latencies = []
throughputs = []
class Benchmarking_per_Epoch(TrainerCallback):

    def on_epoch_begin(self,args,state,control,**kwargs):
        torch.cuda.synchronize()
        self.start_time = time.perf_counter()
    def on_epoch_end(self,args,state,control,**kwargs):
        torch.cuda.synchronize()
        epoch_duration = time.perf_counter() - self.start_time
        #print(f'Time elapsed in epoch(epoch latency) {state.epoch}: {epoch_duration}')
    def on_step_begin(self,args,state,control,**kwargs):
      torch.cuda.synchronize()#pseftika parapano
      self.step_start_time = time.perf_counter()
    def on_step_end(self,args,state,control,**kwargs):
      torch.cuda.synchronize() #perimene na teliosoun oi gpus tous ypologismous gia na mhn stamatiseis na metras eno borei na trexoun akoma oi gpu
      step_latency = time.perf_counter() - self.step_start_time
      #print(f'Step {state.global_step} Latency: {step_latency:.2f}')
      step_throughput = args.per_device_train_batch_size / step_latency #samples in this batch that where processed in latency time
      #assuming 1 step = 1 batch else 1 step = batch_size * gradient_accumulation_steps(default 1)
      #print(f'Step {state.global_step} Throughput: {step_throughput:.2f} samples/sec')
      #mean time / batch , batch1 n1 secs,batch2 n2 secs etc
      latencies.append(step_latency)
      throughputs.append(step_throughput)


##########
training_args = TrainingArguments(
    output_dir="my_awesome_model",
    learning_rate=2e-5,
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,
    num_train_epochs=1, #dokimi giati ta benchmarks pou epistrefei
    weight_decay=0.01,
    eval_strategy="no",#remove evaluation overhead. dont evaluate at every step/batch or epoch
    save_strategy="no", #remove i/o overhead,disk saving overhead by saving checkpoints
    logging_strategy="no",
    #logging_steps = 1
    report_to="none",#
    disable_tqdm=True #remove visualization/progress bar overhead
)
print(training_args.gradient_accumulation_steps)
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_imdb["train"],#already provides a dataloader implicitely
    eval_dataset=tokenized_imdb["test"],
    processing_class=tokenizer,
    compute_metrics=compute_metrics,
    #callbacks=[StepLatencyTrackerTrainerCallback(device='cuda',backend='pytorch')] #callback itself adds small overhead. increases if printing inside the callback
    callbacks=[Benchmarking_per_Epoch()]
    )
############################------TRAINING/FINE-TUNING------------##################
#torch.cuda.syncronize() if there are gpu computations above
start = time.perf_counter() # START COUNTING RIGHT BEFORE FINE-TUNING
results = trainer.train()
torch.cuda.synchronize() # WAIT FOR GPUS to FINISH
print(f'WALL CLOCK TRAINING TIME :{time.perf_counter() - start:.2f}') #### STOP COUNTING AFTER FINE-TUNING
###############ALL THESE FOR ONE EPOCH IT CHANGES FOR >1 EPOCHS##############
######Average batch metrics##############
#print(len(latencies))
print(f'Average Batch/step latency: {sum(latencies)/len(latencies):.2f} seconds per batch/step')
print(f'Average Batch/step throughput: {sum(throughputs)/len(throughputs):.2f} samples per second')
#######Global Trainer metrics#####
print(f'Global Throughput(Trainer): {results.metrics['train_samples_per_second']:.2f} vs Mean of Throughputs: {sum(throughputs)/len(throughputs):.2f}') #Close due to low latencies variance
print(f'Global Latency(Trainer): {results.metrics['train_runtime']:.2f} vs Sum of Latencies: {sum(latencies):.2f}')
########Global Metrics ################
print(f'Global Throughput(total samples/trainer runtime): {len(tokenized_imdb['train'])/results.metrics['train_runtime']:.2f}')
print(f'Number of Model Parameters: {original.num_parameters()}')
#print(f'Number of Model Parameters X Numerical Precision = Model Disk Size: {model.num_parameters*precision}')

###########################--------INFERENCE/EVALUATING ON A TEST SET ##########
latencies = []
torch.cuda.synchronize() #leftover gpu work from earlier
start = time.perf_counter()
eval_results = trainer.evaluate(eval_dataset=tokenized_imdb['test'])
torch.cuda.synchronize()
print(f'WALL CLOCK INFERENCE/EVALUATION TIME :{time.perf_counter() - start:.2f}') #### STOP COUNTING AFTER EVALUATION

######Average batch metrics##############

print(f'Average Batch/step latency: {sum(latencies)/len(latencies):.2f} seconds per batch/step')
print(f'Average Batch/step throughput: {sum(throughputs)/len(throughputs):.2f} samples per second')
#######Global Trainer metrics#####
print(f'Global Throughput(Trainer): {results.metrics['eval_samples_per_second']:.2f} vs Mean of Throughputs: {sum(throughputs)/len(throughputs):.2f}') #Close due to low latencies variance
print(f'Global Latency(Trainer): {results.metrics['eval_runtime']:.2f} vs Sum of Latencies: {sum(latencies):.2f}')
########Global Metrics ################
print(f'Global Throughput(total samples/trainer runtime): {len(tokenized_imdb['test'])/results.metrics['eval_runtime']:.2f}')